package gg.vape.utils.render;

public class TextureAtlasRegion {
    public final int q;
    public final int g;
    public float d;
    public float n;
    public final int p;
    public final int N;
    public float X;
    public float s;

    public TextureAtlasRegion(int n, int n2, int n3, int n4, float f, float f2, float f3, float f4) {
        this.N = n;
        this.p = n2;
        this.q = n3;
        this.g = n4;
        this.d = f;
        this.s = f2;
        this.X = f3;
        this.n = f4;
    }
}

