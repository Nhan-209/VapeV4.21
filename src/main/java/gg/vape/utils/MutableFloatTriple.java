package gg.vape.utils;

public class MutableFloatTriple {
    public float G;
    public float B;
    public float E;

    public void i(float f) {
        this.E = f;
    }

    public float D() {
        return this.B;
    }

    public float H() {
        return this.G;
    }

    public MutableFloatTriple(float f, float f2, float f3) {
        this.B = f;
        this.G = f2;
        this.E = f3;
    }

    public void C(float f) {
        this.B = f;
    }

    public float Q() {
        return this.E;
    }

    public void T(float f) {
        this.G = f;
    }
}

