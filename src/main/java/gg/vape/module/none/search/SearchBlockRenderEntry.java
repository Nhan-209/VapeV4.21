package gg.vape.module.none.search;

public class SearchBlockRenderEntry {
    private int m;
    private int Z;
    private int H;
    private int y;
    private int E;

    public int f() {
        return this.E;
    }

    public int k() {
        return this.Z;
    }

    public int i() {
        return this.H;
    }

    public SearchBlockRenderEntry(int n, int n2, int n3, int n4, int n5) {
        this.m = n;
        this.Z = n2;
        this.H = n3;
        this.E = n4;
        this.y = n5;
    }

    public void L(int n, int n2, int n3, int n4, int n5) {
        this.m = n;
        this.Z = n2;
        this.H = n3;
        this.E = n4;
        this.y = n5;
    }

    public int R() {
        return this.m;
    }

    public int N() {
        return this.y;
    }
}

